<?php

namespace App\Http\Controllers;

use App\Models\Category;
use App\Models\Product;
use App\Services\AICopilot\AICopilotService;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Str;

class AICopilotController extends Controller
{
    protected AICopilotService $copilotService;

    public function __construct(AICopilotService $copilotService)
    {
        $this->copilotService = $copilotService;
    }

    /**
     * Process conversational chat, speech transcript, or image input.
     */
    public function chat(Request $request)
    {
        $request->validate([
            'prompt' => 'required|string|max:2000',
            'image_data' => 'nullable|string',
        ]);

        $prompt = trim($request->input('prompt'));
        $imageData = $request->input('image_data');
        $user = Auth::user();

        $response = $this->copilotService->handleMessage($prompt, $imageData, $user);

        return response()->json([
            'success' => true,
            'reply' => $response['reply'],
            'role' => $response['role'],
            'action' => $response['action'],
            'action_data' => $response['action_data'],
            'suggested_replies' => $response['suggested_replies'],
        ]);
    }

    /**
     * One-Click Publish Product Draft generated by AI Copilot.
     */
    public function publishDraft(Request $request)
    {
        $user = Auth::user();
        if (!$user || !$user->is_seller()) {
            return response()->json(['success' => false, 'message' => 'Only registered sellers can publish products.'], 403);
        }

        if (!$user->canAddProduct()) {
            return response()->json([
                'success' => false,
                'message' => 'Quota limit reached (50/50). Upgrade to Mini-Website for unlimited product listings.',
                'upgrade_required' => true,
            ], 403);
        }

        $request->validate([
            'name' => 'required|string|max:255',
            'price' => 'required|numeric|min:0',
            'category' => 'nullable|string',
            'image_url' => 'nullable|string',
            'size' => 'nullable|string',
        ]);

        $catName = trim($request->input('category', 'General Hardware'));
        $category = Category::whereRaw('LOWER(TRIM(name)) = ?', [strtolower($catName)])->first();
        if (!$category) {
            $category = Category::create([
                'name' => $catName,
                'slug' => Str::slug($catName) . '-' . Str::random(4),
            ]);
        }

        $name = trim($request->input('name'));
        $price = floatval($request->input('price'));
        $mrp = $price * 1.35;
        $imageUrl = $request->input('image_url');

        $product = Product::create([
            'user_id' => $user->id,
            'category_id' => $category->id,
            'name' => $name,
            'slug' => Str::slug($name) . '-' . Str::random(5),
            'sku' => 'AI-' . strtoupper(Str::random(7)),
            'price' => $price,
            'mrp' => $mrp,
            'wholesale_price' => $price,
            'retail_price' => $price * 1.15,
            'stock_quantity' => 100,
            'description' => "Verified industrial wholesale grade {$name}. Listed with AI Catalog Copilot.",
            'image' => $imageUrl,
            'is_active' => true,
        ]);

        return response()->json([
            'success' => true,
            'message' => "✓ '{$product->name}' safaltapoorvak live store me publish ho gaya!",
            'product' => [
                'id' => $product->id,
                'name' => $product->name,
                'price' => $product->price,
                'url' => route('product.show', $product->slug),
            ]
        ]);
    }

    /**
     * Future-Ready AI Voice Calling Webhook (Twilio / Retell AI / Vapi / Bland.ai).
     */
    public function voiceWebhook(Request $request)
    {
        $transcript = $request->input('transcript') ?: $request->input('speech') ?: $request->input('message');
        $callerPhone = $request->input('caller_phone') ?: $request->input('from');

        if (empty($transcript)) {
            return response()->json(['reply' => 'Namaste! Main VyaparIndia AI Assistant hoon. Main aapki kya madad kar sakta hoon?']);
        }

        $response = $this->copilotService->handleMessage($transcript);

        return response()->json([
            'reply' => strip_tags($response['reply']),
            'action' => $response['action'],
            'action_data' => $response['action_data'],
        ]);
    }
}
